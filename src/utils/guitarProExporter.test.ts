import { describe, it, expect } from 'vitest';
import * as alphaTab from '@coderline/alphatab';
import { BeatColumn, InstrumentProfile, TabDocument, TabNote } from '../types/tab';
import { UKULELE_PROFILE } from '../instruments/ukulele';
import { GUITAR_PROFILE, GUITAR_TUNINGS } from '../instruments/guitar';
import { BASS_PROFILE } from '../instruments/bass';
import { createBlankTabDocument } from './sampleData';
import { createChordMarker, getChordPreset } from './musicTheory';
import { exportGuitarPro, getExportFileName } from './guitarProExporter';
import { convertGpChord, convertGpKeySignature, parseGuitarProToTab } from './guitarProImporter';

let noteId = 0;
const n = (string: number, fret: number, extra: Partial<TabNote> = {}): TabNote => ({ id: `n${++noteId}`, string, fret, ...extra });

function docWith(profile: InstrumentProfile, measures: BeatColumn[][], extra: Partial<TabDocument> = {}): TabDocument {
  return {
    ...createBlankTabDocument(profile),
    title: 'Round Trip',
    artist: 'Tester',
    tempo: 104,
    measures: measures.map((beats, i) => ({ id: `m${i + 1}`, index: i + 1, timeSignature: [4, 4], beats })),
    ...extra
  };
}

const roundTrip = (doc: TabDocument, profile: InstrumentProfile) => {
  const bytes = exportGuitarPro(doc);
  return parseGuitarProToTab(bytes.buffer.slice(bytes.byteOffset, bytes.byteOffset + bytes.byteLength) as ArrayBuffer, 'x.gp', profile);
};

// What the round trip keeps of each column (ids are regenerated by the importer)
const columns = (doc: TabDocument) => doc.measures.map(m => m.beats.map(b => ({
  duration: b.duration,
  isDotted: !!b.isDotted,
  isTriplet: !!b.isTriplet,
  isRest: !!b.isRest,
  isTied: !!b.isTied,
  notes: b.notes.map(note => [note.string, note.fret, !!note.isTied]).sort(),
  chord: b.chord ? [b.chord.name, b.chord.frets] : null,
  lyric: b.lyric ?? null
})));

describe('guitarProExporter: round trip through the Guitar Pro importer', () => {
  it('keeps a ukulele song: rhythm, triplets, rests, ties, muted notes, chords, lyrics, meter, tempo and key', () => {
    const doc = docWith(UKULELE_PROFILE, [
      [
        { id: 'a1', duration: '1/8', isTriplet: true, chord: getChordPreset('F')!, notes: [n(4, 2), n(3, 0), n(2, 1), n(1, 0)], lyric: 'one' },
        { id: 'a2', duration: '1/8', isTriplet: true, notes: [n(1, 1)] },
        { id: 'a3', duration: '1/8', isTriplet: true, notes: [n(1, 3)] },
        { id: 'a4', duration: '1/4', isDotted: true, notes: [n(2, 3)] },
        { id: 'a5', duration: '1/8', notes: [n(1, -1), n(2, -1)] },
        { id: 'a6', duration: '1/4', isRest: true, notes: [] }
      ],
      [
        { id: 'b1', duration: '1/2', chord: getChordPreset('Bb')!, notes: [n(4, 3), n(3, 2), n(2, 1), n(1, 1)], lyric: 'two' },
        // The importer detects a chord on every full chord shape, so this column names it too
        { id: 'b2', duration: '1/2', isTied: true, chord: getChordPreset('Bb')!, notes: [n(4, 3, { isTied: true }), n(3, 2, { isTied: true }), n(2, 1, { isTied: true }), n(1, 1, { isTied: true })] }
      ]
    ], { key: 'F' });
    doc.measures[1].timeSignature = [3, 4];

    const imported = roundTrip(doc, UKULELE_PROFILE);
    expect([imported.title, imported.artist, imported.tempo, imported.key, imported.instrument]).toEqual(['Round Trip', 'Tester', 104, 'F', 'ukulele']);
    expect(imported.tuning).toEqual(doc.tuning);
    expect(imported.measures.map(m => m.timeSignature)).toEqual([[4, 4], [3, 4]]);
    expect(columns(imported)).toEqual(columns(doc));
  });

  it('keeps a guitar song with a capo, a custom tuning and its own chord fingering', () => {
    const custom = createChordMarker('Gadd9', [3, 2, 0, 2, 3, 3], undefined, GUITAR_PROFILE);
    const doc = docWith(GUITAR_PROFILE, [[
      { id: 'a1', duration: '1/1', chord: custom, notes: [n(6, 3), n(5, 2), n(4, 0), n(3, 2), n(2, 3), n(1, 3)] }
    ]], { capo: 3, tuning: GUITAR_TUNINGS.DADGAD });

    const imported = roundTrip(doc, GUITAR_PROFILE);
    expect([imported.capo, imported.tuning.key]).toEqual([3, 'DADGAD']);
    expect(columns(imported)).toEqual(columns(doc));
    // The guessed key (Gadd9 shape + capo 3 sounds Bbadd9) is written to the file and comes back as the key
    expect(imported.key).toBe('Bb');
  });

  it('leaves a key without sharps or flats to be guessed again', () => {
    const doc = docWith(GUITAR_PROFILE, [[{ id: 'a1', duration: '1/1', chord: getChordPreset('C', GUITAR_PROFILE)!, notes: [n(5, 3)] }]]);
    expect('key' in roundTrip(doc, GUITAR_PROFILE)).toBe(false);
  });

  it('keeps a bass line', () => {
    const doc = docWith(BASS_PROFILE, [[
      { id: 'a1', duration: '1/4', notes: [n(4, 0)] },
      { id: 'a2', duration: '1/4', notes: [n(3, 2)] },
      { id: 'a3', duration: '1/2', notes: [n(2, 2)] }
    ]]);
    expect(columns(roundTrip(doc, BASS_PROFILE))).toEqual(columns(doc));
  });

  it('writes an empty tied column as the tied continuation of the previous notes', () => {
    const doc = docWith(UKULELE_PROFILE, [[
      { id: 'a1', duration: '1/2', notes: [n(1, 3)] },
      { id: 'a2', duration: '1/2', isTied: true, notes: [] }
    ]]);
    const [, tied] = roundTrip(doc, UKULELE_PROFILE).measures[0].beats;
    expect([tied.isTied, tied.notes.map(note => [note.string, note.fret, note.isTied])]).toEqual([true, [[1, 3, true]]]);
  });

  it('names downloads after the title', () => {
    expect(getExportFileName({ title: 'Three Is a Magic Number' }, 'gp')).toBe('three_is_a_magic_number.gp');
    expect(getExportFileName({ title: '' }, 'uketab')).toBe('untitled.uketab');
  });
});

describe('guitarProImporter: keys and chords from the file', () => {
  it('maps key signatures to keys, leaving C to be guessed', () => {
    expect(convertGpKeySignature(0)).toBeUndefined();
    expect([1, 2, 3, 4, 5, 6, 7].map(convertGpKeySignature)).toEqual(['G', 'D', 'A', 'E', 'B', 'F#', 'Db']);
    expect([-1, -2, -3, -4, -5, -6, -7].map(convertGpKeySignature)).toEqual(['F', 'Bb', 'Eb', 'Ab', 'Db', 'F#', 'B']);
  });

  it('keeps a chord diagram with kept fingering, otherwise takes the library shape of the sounding name', () => {
    const chord = new alphaTab.model.Chord();
    chord.name = 'G';
    chord.strings = [3, 3, 0, 0, 2, 3]; // highest string first
    expect(convertGpChord(chord, true, 6, 2, GUITAR_PROFILE)).toEqual(createChordMarker('G', [3, 2, 0, 0, 3, 3], undefined, GUITAR_PROFILE));
    // Re-voiced from a source with capo 2: the G shape sounds A
    expect(convertGpChord(chord, false, 4, 2, UKULELE_PROFILE)).toEqual(getChordPreset('A', UKULELE_PROFILE));
    chord.name = 'Xyz';
    expect(convertGpChord(chord, false, 4, 0, UKULELE_PROFILE)).toBeNull();
  });
});
